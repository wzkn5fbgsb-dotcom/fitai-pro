export type FoodCategory = 'protein' | 'carb' | 'fat' | 'vegetable' | 'fruit' | 'dairy' | 'legume';

export interface Per100 {
  kcal: number;
  protein: number;
  carbs: number;
  fat: number;
  fiber: number | null; // null = USDA no publica el dato
}

