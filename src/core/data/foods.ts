export const FOOD_BY_ID: Record<string, Food> = Object.fromEntries(FOODS.map((x) => [x.id, x]));

export function getFood(id: string): Food {
  const food = FOOD_BY_ID[id];
  if (!food) throw new Error(`Alimento desconocido: ${id}`);
  return food;
}

/** Relaciona texto libre del usuario ("no como cerdo ni champiñones") con ids de alimentos. */
export function matchFoodsFromText(text: string): string[] {
  const norm = (s: string) =>
    s
      .toLowerCase()
      .normalize('NFD')
      .replace(/[̀-ͯ]/g, '');
  const t = ` ${norm(text)} `;
  const ids = new Set<string>();
  for (const food of FOODS) {
    const names = [food.name.es, food.name.en, ...food.aliases].map(norm);
    if (names.some((n) => n.length >= 3 && new RegExp(`[^a-z]${n.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}s?[^a-z]`).test(t))) {
      ids.add(food.id);
    }
  }
  return [...ids];
}
